"""Pre-outcome randomization checks: sample-ratio mismatch and covariate balance.

Reads the assignment and pre-treatment columns only (the loader's blind mode),
so it can run before the analysis plan is committed without unblinding.
Writes reports/phase0_randomization_checks.md.
"""

from exptools.balance import joint_balance_test, standardized_differences
from exptools.data import ARMS, ASSIGNMENT, CONTROL, PRE_TREATMENT, REPO_ROOT, load_hillstrom
from exptools.srm import srm_test

# The joint test uses the binned history_segment instead of raw history: the
# dollar amount is heavy-tailed (the max is ~21x the median), and a linear logit
# term would be driven by a handful of extreme customers.
JOINT_COVARIATES = [c for c in PRE_TREATMENT if c != "history"]


def main() -> None:
    df = load_hillstrom()  # blind: no outcome columns
    counts = df[ASSIGNMENT].value_counts().to_dict()
    srm = srm_test(counts, {arm: 1 for arm in ARMS})
    smd = standardized_differences(df, ASSIGNMENT, CONTROL, PRE_TREATMENT)
    joint = joint_balance_test(df, ASSIGNMENT, JOINT_COVARIATES)
    worst = smd.loc[smd["z"].abs().idxmax()]

    lines = [
        "# Phase 0: randomization checks (pre-outcome)",
        "",
        "Generated by `scripts/check_randomization.py` from the blind loader: the",
        "assignment column and pre-treatment covariates only, no outcomes.",
        "",
        "## Sample-ratio mismatch",
        "",
        "Design: 1/3 of customers per arm. Alarm threshold: p < 0.001 (pre-registered).",
        "",
        "| Arm | Observed | Expected |",
        "|---|---:|---:|",
        *(f"| {a} | {srm.observed[a]:,} | {srm.expected[a]:,.1f} |" for a in ARMS),
        "",
        f"Chi-square = {srm.chi2:.3f} on {srm.df} df, p = {srm.p_value:.3f}. "
        f"**{'SRM DETECTED' if srm.mismatch else 'No sample-ratio mismatch.'}**",
        "",
        "## Covariate balance",
        "",
        "Standardized mean difference (SMD) of each covariate, e-mail arm vs control.",
        "Under randomization SMD is roughly normal with sd sqrt(1/n_arm + 1/n_control),",
        "about 0.0097 here, so z = SMD / 0.0097 is the right yardstick, not the",
        "observational-study rule of |SMD| > 0.1.",
        "",
        "| Covariate | Mens SMD | Mens z | Womens SMD | Womens z |",
        "|---|---:|---:|---:|---:|",
    ]
    wide = smd.pivot(index="covariate", columns="arm", values=["smd", "z"])
    for cov, row in wide.iterrows():
        cells = [f"{row['smd', arm]:+.4f} | {row['z', arm]:+.2f}" for arm in ("Mens E-Mail", "Womens E-Mail")]
        lines.append(f"| {cov} | {' | '.join(cells)} |")
    lines += [
        "",
        f"Largest |z| is {abs(worst['z']):.2f} ({worst['covariate']}, {worst['arm']}) among",
        f"{len(smd)} comparisons. Those comparisons are correlated (indicator levels of one",
        "variable sum to one, and both arms share the control), so they are judged",
        "together by the joint test below rather than one at a time.",
        "",
        "## Joint balance test",
        "",
        "Multinomial logit of arm on all pre-treatment covariates (history_segment",
        "dummies in place of raw history), likelihood-ratio test against intercept-only.",
        "Under valid randomization the p-value is uniform on (0, 1).",
        "",
        f"LR = {joint.lr_stat:.2f} on {joint.df} df, **p = {joint.p_value:.3f}**.",
        "",
    ]
    out = REPO_ROOT / "reports" / "phase0_randomization_checks.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
